def main():
    seen = set()
    chosen = []  # (group, adverb, meaning)
    skipped = []
    for group, items in GROUPS:
        for word, meaning in items:
            key = word.lower().strip()
            if not key.endswith("ly") or " " in key:
                skipped.append((word, "not a single -ly adverb"))
                continue
            if key in seen:
                skipped.append((word, "duplicate"))
                continue
            if meaning.lower().startswith("already"):
                skipped.append((word, "marked duplicate"))
                continue
            seen.add(key)
            chosen.append((group, word, meaning))

    print(f"unique -ly adverbs: {len(chosen)}")
    print(f"skipped: {len(skipped)}")
    if len(chosen) < 500:
        raise SystemExit(f"need 500, have {len(chosen)}")
    chosen = chosen[:500]

    # regroup preserving order
    order = []
    buckets = {}
    for group, word, meaning in chosen:
        if group not in buckets:
            order.append(group)
            buckets[group] = []
        buckets[group].append((word, meaning))

    lines = [
        '      <section id="saidly">',
        '        <h2>94. 500 Words after &ldquo;Said&rdquo; (-ly)</h2>',
        '        <p class="note">Manner adverbs for the beat after a line of dialogue: &ldquo;What if we lose?&rdquo; Clara said <em>solemnly</em>. The adverb is how the line was spoken, not a replacement for <em>said</em>. Grouped by tone. A few also appear in the empathy list (&sect;38); here they are filed as dialogue delivery.</p>',
    ]
    n = 1
    for group in order:
        lines.append('        <div class="entry filterable">')
        lines.append(f"          <h3>{group}</h3>")
        lines.append('          <ul class="def-list">')
        for word, meaning in buckets[group]:
            lines.append(f"            <li><strong>{n}. {word}</strong> \u2013 {meaning}</li>")
            n += 1
        lines.append("          </ul>")
        lines.append("        </div>")
    lines.append("      </section>")
    lines.append("")

    out = Path(__file__).with_name("_saidly_section.html")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", out.name, "entries", n - 1)
    for group in order:
        print(f"  {group}: {len(buckets[group])}")


